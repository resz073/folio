import asyncio, sys
sys.path.insert(0, 'tests')
from harness import *
async def main():
    async with async_playwright() as p:
        b, page, errors = await new_page(p, width=1400, height=1000)
        await load(page)
        await page.evaluate("() => __Q.newFromTemplate('letter')")
        await page.wait_for_timeout(300)
        await page.evaluate("() => __Q.CMD.fillFields()")
        await page.wait_for_timeout(200)
        names = await page.evaluate("() => Array.from(document.querySelectorAll('.fields-list .fld')).map(f => f.querySelector('.flabel').textContent + ' / ' + f.querySelector('.link-btn').textContent)")
        print('fields:', names)
        await page.screenshot(path='shots/fields-pane.png')
        # fill one through the pane
        await page.fill('.fields-list input[aria-label="Recipient Name"]', 'Mr. Kamal Hossain')
        await page.press('.fields-list input[aria-label="Recipient Name"]', 'Enter')
        await page.wait_for_timeout(200)
        r = await page.evaluate("() => ({ inDoc: document.getElementById('editor').textContent.includes('Mr. Kamal Hossain'), left: document.getElementById('editor').textContent.includes('[Recipient Name]'), remembered: __Q.Prefs.fieldValues, focused: document.activeElement.getAttribute('aria-label') })")
        print('after fill:', r)
        # undo restores the field
        await page.evaluate("() => __Q.undo()")
        await page.wait_for_timeout(100)
        print('undo restores:', await page.evaluate("() => document.getElementById('editor').textContent.includes('[Recipient Name]')"))
        # suggestion after one letter in a fresh letter
        await page.evaluate("() => __Q.newFromTemplate('letter')")
        await page.wait_for_timeout(900)
        await page.click('.fields-list input[aria-label="Recipient Name"]')
        await page.keyboard.type('k')
        await page.wait_for_timeout(100)
        sug = await page.evaluate("() => Array.from(document.querySelectorAll('.fld-sug:not([hidden]) .fld-opt')).map(o => o.textContent)")
        print('suggest for "k":', sug)
        await page.screenshot(path='shots/fields-suggest.png')
        await page.click('.fld-sug:not([hidden]) .fld-opt')
        await page.wait_for_timeout(150)
        print('picked suggestion fills doc:', await page.evaluate("() => document.getElementById('editor').textContent.includes('Mr. Kamal Hossain')"))
        # click-to-select and F11 / Tab navigation in the page
        await page.evaluate("() => __Q.newFromTemplate('letter')")
        await page.wait_for_timeout(300)
        box = await page.evaluate("""() => { const w = document.createTreeWalker(document.getElementById('editor'), NodeFilter.SHOW_TEXT); let n; while ((n = w.nextNode())) { const i = n.data.indexOf('[Title]'); if (i >= 0) { const r = document.createRange(); r.setStart(n, i + 3); r.setEnd(n, i + 4); const b = r.getBoundingClientRect(); return { x: b.left + b.width / 2, y: b.top + b.height / 2 }; } } return null; }""")
        await page.mouse.click(box['x'], box['y'])
        await page.wait_for_timeout(150)
        print('click selects:', repr(await page.evaluate("() => getSelection().toString()")))
        await page.keyboard.press('Tab')
        print('tab → next:', repr(await page.evaluate("() => getSelection().toString()")))
        await page.keyboard.press('F11')
        print('F11 → next:', repr(await page.evaluate("() => getSelection().toString()")))
        await page.keyboard.press('Shift+F11')
        print('Shift+F11 → prev:', repr(await page.evaluate("() => getSelection().toString()")))
        await page.keyboard.type('Dhaka Bank Ltd.')
        print('typed over field:', await page.evaluate("() => document.getElementById('editor').textContent.includes('Dhaka Bank Ltd.')"))
        # insert field dialog
        await page.evaluate("() => { const ed = document.getElementById('editor'); const p = ed.lastElementChild; const r = document.createRange(); r.selectNodeContents(p); r.collapse(false); getSelection().removeAllRanges(); getSelection().addRange(r); ed.focus(); __Q.CMD.insertField(); }")
        await page.wait_for_timeout(150)
        await page.keyboard.type('Reference No')
        await page.keyboard.press('Enter')
        await page.wait_for_timeout(150)
        print('inserted field selected:', repr(await page.evaluate("() => getSelection().toString()")))
        for e in errors: print('ERR', e)
        await b.close()
asyncio.run(main())
