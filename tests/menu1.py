"""The right-click menu, as in Word: text (cut/copy/paste, Font, Paragraph, Link, comment),
a right-click keeping or moving the selection, links, table cells (Insert, Delete, Merge,
Select, Cell Alignment, AutoFit, Borders and Shading), keyboard use, Shift+right-click for the
browser's menu, pictures, tracked changes, fields, comments and read-only documents."""
import asyncio, sys, json, base64
sys.path.insert(0, 'tests')
from harness import *
from tbl1 import HELPERS

fails = []
def ok(cond, what, got=None):
    print(('  ok   ' if cond else '  FAIL ') + what + ('' if cond or got is None else '  -> ' + json.dumps(got, ensure_ascii=False)))
    if not cond: fails.append(what)

PNG = base64.b64encode(bytes.fromhex('89504e470d0a1a0a0000000d4948445200000010000000100802000000909168360000001d49444154789c63fccfc0f09f8114c0c4400a60a2a6603aa9188c0000a5a10a1d58b6e0610000000049454e44ae426082')).decode()
HTML = ("<p>Dear Sir, please find the <a href=\"https://example.com/prices\">price list</a> below.</p>"
        "<table class=\"tbl-grid\" style=\"width:100%\"><colgroup><col style=\"width:20%\"><col style=\"width:50%\"><col style=\"width:30%\"></colgroup><tbody>"
        "<tr><td><p>No.</p></td><td><p>Item</p></td><td><p>Amount</p></td></tr>"
        "<tr><td><p>1</p></td><td><p>Paper</p></td><td><p>1,200.00</p></td></tr>"
        "<tr><td><p>2</p></td><td><p>Toner</p></td><td><p>4,500.5</p></td></tr></tbody></table>"
        f"<p>Fill in [Name] here. <img src=\"data:image/png;base64,{PNG}\" style=\"width:40px\"> end.</p><p>Last line of the letter.</p>")

async def main():
    async with async_playwright() as p:
        b, page, errors = await new_page(p, width=1300, height=950)
        await page.context.grant_permissions(['clipboard-read', 'clipboard-write'])
        await load(page)
        await page.evaluate("h => __Q.openDoc(__Q.newDocModel({ title: 'Menu', html: h }))", HTML)
        await page.wait_for_timeout(400)
        await page.evaluate(HELPERS)
        st = lambda js: page.evaluate(js)
        menu = lambda: st("() => [...document.querySelectorAll('.pop.ctx')].map(p => [...p.querySelectorAll(':scope > .mi')].map(m => m.querySelector('.lb').textContent + (m.disabled ? ' (off)' : '')))")
        async def rclick(x, y, shift=False):
            if shift: await page.keyboard.down('Shift')
            await page.mouse.click(x, y, button='right')
            if shift: await page.keyboard.up('Shift')
            await page.wait_for_timeout(200)
        async def pick(*labels):
            for i, l in enumerate(labels):
                loc = page.locator(f'.pop.ctx[data-level="{i}"] .mi', has_text=l).first
                if i < len(labels) - 1: await loc.hover(); await page.wait_for_timeout(250)
                else: await loc.click()
            await page.wait_for_timeout(250)
        def word_xy(js_text_node, off):
            return st(f"() => {{ const t = {js_text_node}; const r = document.createRange(); r.setStart(t, {off}); r.setEnd(t, {off} + 1); const x = r.getBoundingClientRect(); return [x.left + x.width / 2, x.top + x.height / 2]; }}")
        P1 = "document.querySelector('#editor > p').firstChild"

        print('1. text')
        await rclick(*(await word_xy(P1, 3)))
        m = await menu()
        ok(m and m[0][:4] == ['Cut (off)', 'Copy (off)', 'Paste', 'Paste Options'] and 'Font…' in m[0] and 'Paragraph…' in m[0] and 'New Comment' in m[0], 'the text menu: Cut/Copy (off without a selection), Paste, Paste Options, Font, Paragraph, Link, New Comment', m)
        ok(await st("() => !!document.querySelector('.pop.ctx .mnote')"), 'with a note about Shift+right-click for spelling')
        await page.keyboard.press('Escape'); await page.wait_for_timeout(100)
        ok(await menu() == [], 'Esc closes it')
        await page.mouse.dblclick(*(await word_xy(P1, 1)))   # "Dear"
        await page.wait_for_timeout(100)
        await rclick(*(await word_xy(P1, 2)))
        sel = await st("() => getSelection().toString()")
        ok(sel == 'Dear', 'a right-click on the selected word keeps it selected', sel)
        m = await menu()
        ok(m and m[0][:2] == ['Cut', 'Copy'], 'and Cut and Copy are on', m)
        await pick('Copy')
        clip = await st("async () => (await navigator.clipboard.readText())")
        ok(clip == 'Dear', 'Copy copies it', clip)
        await rclick(*(await word_xy(P1, 10)))
        here = await st("() => { const r = getSelection().getRangeAt(0); return [r.collapsed, r.startOffset]; }")
        ok(here[0] and abs(here[1] - 10) <= 1, 'a right-click elsewhere puts the caret there', here)
        await pick('Paste')
        txt = await st(f"() => {P1}.data.slice(0, 16)")
        ok(txt.startswith('Dear Sir, Dear') or txt.startswith('Dear Sir,Dear') or 'Dear' in txt[8:], 'Paste from the menu pastes (where the page may read the clipboard)', txt)
        await page.keyboard.press('Control+z'); await page.wait_for_timeout(150)
        await rclick(*(await word_xy(P1, 5)))
        await pick('Paragraph…')
        ok(await st("() => [...document.querySelectorAll('.dlg h2, .dialog h2, [role=dialog] h2')].map(x => x.textContent).join()") == 'Paragraph', 'Paragraph… opens the Paragraph dialog')
        opts = await st("() => [...document.querySelectorAll('#dpAlign option, [role=dialog] select option')].map(o => o.value)")
        ok('decimal' in opts, 'whose Alignment list has Decimal point', opts)
        await page.keyboard.press('Escape'); await page.wait_for_timeout(150)
        await rclick(*(await word_xy(P1, 5)))
        await pick('Font…')
        ok(await st("() => [...document.querySelectorAll('[role=dialog] h2')].map(x => x.textContent).join()") == 'Font', 'Font… opens the Font dialog')
        await page.keyboard.press('Escape'); await page.wait_for_timeout(150)

        print('2. links')
        A = "document.querySelector('#editor a').firstChild"
        await rclick(*(await word_xy(A, 2)))
        m = await menu()
        ok(all(x in m[0] for x in ['Edit Link…', 'Open Link', 'Copy Link', 'Remove Link']), 'on a link: Edit, Open, Copy, Remove', m)
        await pick('Copy Link')
        ok(await st("async () => (await navigator.clipboard.readText())") == 'https://example.com/prices', 'Copy Link copies the address')
        await rclick(*(await word_xy(A, 2)))
        await pick('Remove Link')
        ok(await st("() => document.querySelectorAll('#editor a').length") == 0, 'Remove Link removes it')
        await page.keyboard.press('Control+z'); await page.wait_for_timeout(150)

        print('3. tables')
        c = lambda r, k: st(f"() => {{ const x = T.cell(T.tbl(), {r}, {k}).getBoundingClientRect(); return [x.left + x.width * 0.6, x.top + x.height / 2]; }}")
        await rclick(*(await c(1, 1)))
        m = await menu()
        ok(all(x in m[0] for x in ['Insert', 'Delete', 'Split Cells…', 'Select', 'Cell Alignment', 'AutoFit', 'Borders and Shading…']) and 'Merge Cells' not in m[0], 'in a cell: Insert, Delete, Split Cells, Select, Cell Alignment, AutoFit, Borders and Shading', m)
        await pick('Insert', 'Insert Rows Below')
        ok(await st("() => __Q.Tables.grid(T.tbl()).rows.length") == 4, 'Insert › Insert Rows Below adds a row')
        await rclick(*(await c(2, 1)))
        await pick('Delete', 'Delete Rows')
        ok(await st("() => __Q.Tables.grid(T.tbl()).rows.length") == 3, 'Delete › Delete Rows takes it out')
        await rclick(*(await c(1, 2)))
        await pick('Select', 'Select Column')
        ok(await st("() => __Q.Tables.active() && [__Q.Tables.sel.r1, __Q.Tables.sel.c1, __Q.Tables.sel.r2, __Q.Tables.sel.c2]") == [0, 2, 2, 2], 'Select › Select Column selects the column')
        await rclick(*(await c(2, 2)))
        ok(await st("() => __Q.Tables.active() && [__Q.Tables.sel.r1, __Q.Tables.sel.c1, __Q.Tables.sel.r2, __Q.Tables.sel.c2]") == [0, 2, 2, 2], 'a right-click inside the selected cells keeps them selected')
        m = await menu()
        ok('Merge Cells' in m[0], 'and offers Merge Cells', m)
        await page.locator('.pop.ctx[data-level="0"] .mi', has_text='Cell Alignment').hover(); await page.wait_for_timeout(250)
        await page.locator('.pop.ctx .cg[title="Align Center"]').click(); await page.wait_for_timeout(250)
        va = await st("() => [0, 1, 2].map(r => { const c = T.cell(T.tbl(), r, 2); return c.style.verticalAlign + '/' + getComputedStyle(c.querySelector('p')).textAlign; })")
        ok(va == ['middle/center'] * 3, 'Cell Alignment › Align Center centres the column both ways', va)
        await rclick(*(await c(1, 2)))
        await pick('Cell Alignment', 'Numbers on the Decimal Point')
        da = await st("() => [0, 1, 2].map(r => T.cell(T.tbl(), r, 2).querySelector('p').getAttribute('data-align'))")
        ok(da == ['decimal'] * 3, 'Cell Alignment › Numbers on the Decimal Point', da)
        await rclick(*(await c(1, 2)))
        await pick('AutoFit', 'AutoFit Contents')
        ok(await st("() => __Q.Tables.fitMode(T.tbl())") == 'contents', 'AutoFit › AutoFit Contents')
        await page.keyboard.press('Control+z'); await page.wait_for_timeout(200)
        await rclick(*(await c(1, 1)))
        await pick('Borders and Shading…')
        ok(await st("() => [...document.querySelectorAll('[role=dialog] h2')].map(x => x.textContent).join()") == 'Borders and Shading', 'Borders and Shading… opens its dialog')
        await page.keyboard.press('Escape'); await page.wait_for_timeout(150)

        print('4. keyboard')
        await page.mouse.click(*(await word_xy(P1, 5))); await page.wait_for_timeout(100)
        await page.keyboard.press('Shift+F10'); await page.wait_for_timeout(250)
        ok(len(await menu()) == 1, 'Shift+F10 opens the menu at the caret')
        await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown')
        cur = await st("() => document.querySelector('.pop.ctx .mi.kb .lb').textContent")
        ok(cur == 'Paste Options', 'arrows move through the items (skipping ones that are off)', cur)
        await page.keyboard.press('ArrowRight'); await page.wait_for_timeout(150)
        ok(len(await menu()) == 2, 'Right opens the submenu')
        await page.keyboard.press('ArrowLeft'); await page.wait_for_timeout(100)
        ok(len(await menu()) == 1, 'Left closes it')
        await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown')
        await page.keyboard.press('Enter'); await page.wait_for_timeout(300)
        ok(await st("() => [...document.querySelectorAll('[role=dialog] h2')].map(x => x.textContent).join()") == 'Paragraph' and await menu() == [], 'Enter runs the item (Paragraph…)')
        await page.keyboard.press('Escape'); await page.wait_for_timeout(150)
        prevented = await st("""() => { const ev = new MouseEvent('contextmenu', { bubbles: true, cancelable: true, shiftKey: true, clientX: 300, clientY: 300 }); document.querySelector('#editor > p').dispatchEvent(ev); return ev.defaultPrevented; }""")
        ok(prevented is False and await menu() == [], "Shift+right-click leaves the browser's own menu")

        print('5. picture, tracked change, field, comment, read-only')
        img = await st("() => { const r = document.querySelector('#editor img').getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2]; }")
        await rclick(*img)
        m = await menu()
        ok(all(x in m[0] for x in ['Change Picture…', 'Wrap Text', 'Reset Size', 'Alt Text…', 'Delete Picture']) and 'Font…' not in m[0], 'on a picture: Change, Wrap Text, Reset Size, Alt Text, Delete', m)
        await pick('Delete Picture')
        ok(await st("() => document.querySelectorAll('#editor img').length") == 0, 'Delete Picture removes it')
        await page.keyboard.press('Control+z'); await page.wait_for_timeout(150)
        F = "[...document.querySelectorAll('#editor > p')].find(p => p.textContent.includes('[Name]')).firstChild"
        await rclick(*(await word_xy(F, 10)))
        m = await menu()
        ok(all(x in m[0] for x in ['Fill Fields…', 'Next Field']), 'in a field: Fill Fields and Next Field', m)
        await page.keyboard.press('Escape')
        await page.evaluate("() => { __Q.S.track = true; }")
        L = "[...document.querySelectorAll('#editor > p')].pop()"
        await page.mouse.click(*(await word_xy(L + ".firstChild", 4))); await page.keyboard.press('End')
        await page.keyboard.type(' Thanks'); await page.wait_for_timeout(200)
        await page.evaluate("() => { __Q.S.track = false; }")
        ins = await st(f"() => {{ const i = {L}.querySelector('ins.tc'); const r = document.createRange(); r.selectNodeContents(i); const x = r.getBoundingClientRect(); return i ? [x.left + 8, x.top + x.height / 2] : null; }}")
        await rclick(*ins)
        m = await menu()
        ok('Accept Insertion' in m[0] and 'Reject Insertion' in m[0], 'on a tracked insertion: Accept and Reject', m)
        await pick('Accept Insertion')
        ok(await st(f"() => !{L}.querySelector('ins.tc') && {L}.textContent.endsWith(' Thanks')"), 'Accept Insertion keeps the text and the mark goes')
        await page.mouse.dblclick(*(await word_xy(L + ".firstChild", 1))); await page.wait_for_timeout(100)
        await page.evaluate("() => __Q.Comments.add()"); await page.wait_for_timeout(300)
        await page.evaluate("() => { const c = __Q.S.doc.comments[__Q.S.doc.comments.length - 1]; __Q.Comments.save(c.id, 'Check this line'); }")
        await page.wait_for_timeout(150)
        cm = await st("() => { const c = document.querySelector('#editor span.cmt'); const r = c.getBoundingClientRect(); return [r.left + 4, r.top + r.height / 2]; }")
        await rclick(*cm)
        m = await menu()
        ok(all(x in m[0] for x in ['Show Comment', 'Delete Comment']), 'on commented text: Show Comment and Delete Comment', m)
        await page.keyboard.press('Escape')
        await page.evaluate("() => { __Q.S.readOnly = true; }")
        await rclick(*(await word_xy(P1, 5)))
        m = await menu()
        ok('Paste (off)' in m[0] and 'New Comment (off)' in m[0] and 'Font…' in m[0], 'read-only: editing items are off', m)
        await page.keyboard.press('Escape')
        await page.evaluate("() => { __Q.S.readOnly = false; }")
        await page.screenshot(path='shots/menu1.png')
        for e in errors: print('   ERR', e)
        ok(not [e for e in errors if e[0] == 'pageerror'], 'no page errors')
        await b.close()
    print('MENU1', 'OK' if not fails else 'FAILED: ' + '; '.join(fails))

asyncio.run(main())
